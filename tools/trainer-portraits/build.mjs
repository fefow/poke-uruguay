// Packs the PixelLab battle portraits (tools/trainer-portraits/<look>.png, 96x96) into src/gfx/trainer-portraits-data.ts.
// Run: node tools/trainer-portraits/build.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith('.png')).sort();
const lines = files.map((f) => `  ${JSON.stringify(f.slice(0, -4).replace(/^back_/, 'back:'))}: 'data:image/png;base64,${readFileSync(dir + f).toString('base64')}',`);
writeFileSync(new URL('../../src/gfx/trainer-portraits-data.ts', import.meta.url),
  `// Generated by tools/trainer-portraits/build.mjs from the PNGs in that folder: do not edit by hand.\n// Battle portraits (96x96, PixelLab) keyed by character look; 'back:<look>' is the player seen from behind.\nexport const TRAINER_PORTRAITS: Record<string, string> = {\n${lines.join('\n')}\n};\n`);
console.log(`${files.length} portraits`);
