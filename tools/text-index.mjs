// Lists every plain text line the game says (say(...) calls and NPC text/deny fields) so the text editor can show and replace them.
// Writes src/gen/text-index.js. Run by build.mjs; the result is committed so typecheck works without a build.
import ts from 'typescript';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const FILES = readdirSync('src/data').filter((f) => f.endsWith('.ts')).map((f) => `src/data/${f}`).concat(readdirSync('src/game').filter((f) => f.endsWith('.ts')).map((f) => `src/game/${f}`));
const lit = (n) => (n && (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) ? n.text : null);
const lines = (n) => {
  if (!n) return [];
  const one = lit(n);
  if (one !== null) return [one];
  if (ts.isArrayLiteralExpression(n)) return n.elements.map(lit).filter((x) => x !== null);
  return [];
};
const nameOf = (n) => (n && (ts.isIdentifier(n) || ts.isStringLiteral(n)) ? n.text : null);
const prop = (o, key) => { if (!o || !ts.isObjectLiteralExpression(o)) return null; const p = o.properties.find((q) => ts.isPropertyAssignment(q) && nameOf(q.name) === key); return p ? p.initializer : null; };

const found = []; // {text, file, line, ctx, who}
for (const file of FILES) {
  const src = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const lineOf = (n) => src.getLineAndCharacterOfPosition(n.getStart()).line + 1;
  const fnName = (n) => {
    for (let p = n.parent; p; p = p.parent) {
      if ((ts.isMethodDeclaration(p) || ts.isFunctionDeclaration(p)) && p.name && nameOf(p.name)) return nameOf(p.name);
      if (ts.isPropertyAssignment(p) && (ts.isArrowFunction(p.initializer) || ts.isFunctionExpression(p.initializer))) return nameOf(p.name);
      if (ts.isVariableDeclaration(p) && p.initializer && (ts.isArrowFunction(p.initializer) || ts.isFunctionExpression(p.initializer)) && ts.isIdentifier(p.name)) return p.name.text;
    }
    return null;
  };
  const npcOf = (n) => { // object literal with look/name around a text field
    const o = n.parent?.parent;
    if (!o || !ts.isObjectLiteralExpression(o)) return null;
    const look = lit(prop(o, 'look')), name = lit(prop(o, 'name')), script = lit(prop(o, 'script'));
    return [name, look && `aspecto ${look}`, script && `evento ${script}`].filter(Boolean).join(', ') || null;
  };
  const visit = (n) => {
    if (ts.isCallExpression(n)) {
      const c = n.expression;
      const callee = ts.isIdentifier(c) ? c.text : ts.isPropertyAccessExpression(c) ? c.name.text : '';
      if (callee === 'say') {
        const who = lit(prop(n.arguments[1], 'name')) || '';
        for (const t of lines(n.arguments[0])) found.push({ text: t, file, line: lineOf(n), ctx: fnName(n) || 'texto suelto', who });
      }
    } else if (ts.isPropertyAssignment(n) && ['text', 'deny'].includes(nameOf(n.name))) {
      const who = lit(prop(n.parent, 'name')) || '';
      for (const t of lines(n.initializer)) found.push({ text: t, file, line: lineOf(n), ctx: npcOf(n.initializer) ? `Persona (${npcOf(n.initializer)})` : fnName(n) || 'Persona', who });
    }
    ts.forEachChild(n, visit);
  };
  visit(src);
}
// One entry per distinct line: changing it changes it everywhere it is said.
const by = new Map();
for (const f of found) {
  if (!f.text.trim()) continue;
  const e = by.get(f.text) ?? { text: f.text, uses: [] };
  if (!e.uses.some((u) => u.file === f.file && u.line === f.line)) e.uses.push({ file: f.file.replace('src/', ''), line: f.line, ctx: f.ctx, who: f.who });
  by.set(f.text, e);
}
const list = [...by.values()];
writeFileSync('src/gen/text-index.js', `// Generated by tools/text-index.mjs (do not edit): every plain text line of the game and where it is said.\nexport const TEXT_INDEX = ${JSON.stringify(list)};\n`);
console.log(`text index: ${list.length} lines`);
